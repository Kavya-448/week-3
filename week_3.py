from google import genai
from google.colab import userdata

try:
    # Load Gemini API key
    api_key = userdata.get("GEMINI_API_KEY")

    if not api_key:
        raise ValueError("GEMINI_API_KEY not found")

    client = genai.Client(api_key=api_key)

    print("Environment ready. Starting prompt refinement...")

    # Function to send prompt to Gemini
    def ask_llm(prompt):
        response = client.models.generate_content(
            model="gemini-flash-lite-latest",
            contents=prompt,
            config={"temperature": 0.5}
        )
        return response.text

    # Iteration 0: Baseline prompt
    prompt0 = "Explain photosynthesis to a 10-year-old."

    # Iteration 1: Add analogy and short explanation
    prompt1 = (
        "You are a friendly science teacher. Explain photosynthesis "
        "to a 10-year-old using a simple analogy. Use 3 short sentences "
        "and avoid difficult words."
    )

    # Iteration 2: Add memory trick and diagram description
    prompt2 = (
        "You are a friendly science teacher. Explain photosynthesis "
        "to a 10-year-old using a simple analogy in 3 short sentences. "
        "Avoid difficult words. Add a memorable trick and describe "
        "a simple text-only diagram."
    )

    prompts = [prompt0, prompt1, prompt2]

    analyses = [
        "Baseline: A basic explanation; it may need simpler language.",
        "Refinement 1: Adds an analogy, simple words, and a length limit.",
        "Refinement 2: Adds a memory trick and diagram description."
    ]

    responses = []

    # Generate and display all responses
    for i, prompt in enumerate(prompts):
        print("\n" + "=" * 45)
        print(f"ITERATION {i}")
        print("=" * 45)

        print("\nPrompt:")
        print(prompt)

        try:
            answer = ask_llm(prompt)
            responses.append(answer)

            print("\nResponse:")
            print(answer)

            print("\nAnalysis:")
            print(analyses[i])

        except Exception as e:
            responses.append(None)
            print("\nAPI/Network Error:", e)
            print("Please check model availability and try again.")

    # Final summary
    print("\n" + "=" * 45)
    print("FINAL SUMMARY")
    print("=" * 45)

    print("Iteration 0: Basic explanation.")
    print("Iteration 1: Improved simplicity and clarity.")
    print("Iteration 2: Added memory aid and visual guidance.")

    print("\nTotal successful responses:",
          sum(r is not None for r in responses), "out of 3")

except ValueError as e:
    print("Error:", e)

except Exception as e:
    print("API/Network Error:", e)